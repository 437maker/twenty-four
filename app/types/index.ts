// index.ts — TypeScript type definitions for the whole app.
//
// Think of these as blueprints. When you say a variable is of type "Task",
// TypeScript will enforce that it has exactly these fields and no others.
// This catches typos and wrong data shapes before they cause bugs at runtime.

// A Pillar is one of the three life areas we track.
// The pipe "|" means "or" — it can be one of these three string values.
export type Pillar = 'work' | 'personal' | 'sleep';

// A Task is one planned activity on a specific day.
export interface Task {
  id: number;             // Auto-generated by the database
  date: string;           // "YYYY-MM-DD" — e.g. "2024-03-15"
  name: string;           // e.g. "Morning deep work"
  start_time: string;     // "HH:MM" — e.g. "09:00"
  duration_hours: number; // e.g. 2.5 means two and a half hours
  pillar: Pillar;         // which of the three pillars this belongs to
  completed: boolean;     // has the user checked this off?
  created_at: string;     // when the task was created (ISO date string)
}

// Settings stores the user's preferences and streak progress.
// There is only ONE row of settings — for this user, on this device.
export interface Settings {
  companion_name: string;         // e.g. "Nova"
  work_target_hours: number;      // daily work goal
  personal_target_hours: number;  // daily personal time goal
  sleep_target_hours: number;     // daily sleep goal
  current_streak: number;         // days in a row with at least one completed task
  longest_streak: number;         // all-time best streak
  last_active_date: string | null; // last day the user completed a task
  onboarded: boolean;             // has the user finished the first-launch setup?
  notification_time: string;      // "HH:MM" — when the daily reminder fires
}

// NewTaskInput is what we need to create a task.
// It's the same as Task but without the fields the database generates (id, created_at).
export interface NewTaskInput {
  date: string;
  name: string;
  start_time: string;
  duration_hours: number;
  pillar: Pillar;
}
